<h1 id="accessibility">Accessibility</h1>

<p>Windows 10 has the following accessibility features:</p>

<ul>
	<li>
		<b>Magnifier: </b>enlarges items or your entire screen so text and images are  
		easier to see.
	</li>
	<li>
		<b>Narrator: </b>a built-in screen reader that reads aloud text on your screen 
		and describes events.
	</li>
	<li>
		<b>Color Filters: </b>changes screen colors to help users with color blindness (such 
		as deuteranopia or protanopia) or light sensitivity.
	</li>
	<li>
		<b>High Contrast: </b>applies high-contrast color themes to make text and apps stand 
		out clearly.
	</li>
	<li>
		<b>Text and Cursor Size: </b>adjusts text scaling across the system and changes the 
		size or color of the mouse pointer. 
	</li>
	<li>
		<b>Mono Audio: </b>combines stereo channels into a single mono track so you hear all 
		sound even with one earphone or hearing loss in one ear.
	</li>
	<li>
		<b>Visual Notifications: </b>flashes the active window or the screen to give a visual 
		cue when an audio alert goes off.
	</li>
	<li>
		<b>Closed Captions: </b>customizes how subtitles and captions appear in supported apps 
		and videos. 
	</li>
	<li>
		<b>Speech Recognition: </b>lets you control your PC using only your voice.
	</li>
	<li>
		<b>On-Screen Keyboard: </b>allows you to type by clicking an interactive virtual 
		keyboard with a mouse or touch input.
	</li>
	<li>
		<b>Sticky Keys and Filter Keys: </b>simplifies complex keyboard shortcuts (like Ctrl + 
		Alt + Delete) by letting you press keys one at a time.
	</li>
	<li>										
		<b>Mouse Keys: </b>lets you move and control the mouse cursor using your numeric keypad.
	</li>
</ul>

<p>If you need help using these features, one of our friendly digital mentors can assist 
you with turning them on and adjusting them to suit your needs.</p>
						
<p>We can also project your computer screen onto a larger TV screen. This can be 
particularly helpful if you find the built-in screen magnifier difficult to use or 
simply need a larger view of what is on your screen.</p>

<p><img src="images/WindowsTV.jpg" alt="WindowsTV.jpg" height="200" /></p>

<p>One of our digital mentors will help you set this up.</p>

